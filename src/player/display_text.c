void display_text_ascii(const char *in, char *out, size_t bytes, bool dos_names)
{
    if (!bytes)
        return;
    size_t n = 0;
    while (*in && n + 1 < bytes)
    {
        unsigned c = (unsigned char)*in++;
        if (c >= 128 && dos_names)
            c = cp437[c - 128];
        else if (c >= 192 && c < 245)
        {
            unsigned count = c < 224 ? 1 : c < 240 ? 2 : 3, code = c & ((1U << (6 - count)) - 1);
            bool valid = true;
            for (unsigned i = 0; i < count; ++i)
            {
                if (!in[i] || ((unsigned char)in[i] & 192) != 128)
                {
                    valid = false;
                    break;
                }
                code = (code << 6) | ((unsigned char)in[i] & 63);
            }
            if (valid)
            {
                in += count;
                c = code;
            }
        }
        if (c >= 0x300 && c <= 0x36f)
            continue;
        if (c >= 32 && c < 127)
            out[n++] = (char)c;
        else
        {
            const char *s = fold(c);
            if (s)
                while (*s && n + 1 < bytes)
                    out[n++] = *s++;
            else if (c < 32)
                out[n++] = ' ';
            else
                out[n++] = '?';
        }
    }
    out[n] = 0;
}
